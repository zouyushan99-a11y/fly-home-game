"""Original, deterministic, seamless overhead materials. No external images."""
from pathlib import Path
from PIL import Image, ImageDraw
import math,random,json,base64,io
root=Path(__file__).resolve().parents[1];out=root/'assets/ground';out.mkdir(exist_ok=True)
colors={'asphalt':(86,93,96),'paving':(183,181,164),'curb':(157,158,147),'grass':(125,145,100)};images={};embedded={}
for n,(kind,base) in enumerate(colors.items()):
 im=Image.new('RGB',(256,256));px=im.load();rng=random.Random(704+n)
 for y in range(255):
  for x in range(255):
   wave=2*math.sin(x*math.tau/255)+2*math.cos(y*math.tau/255)+math.sin((x+y)*math.tau*3/255)
   noise=rng.uniform(-6,6)+wave
   if kind=='paving':
    row=int(y/31.875);u=(x+(15.9375 if row%2 else 0))%31.875
    if u<1.1 or y%31.875<1.1:noise-=25
   if kind=='curb' and x%63.75<1.2:noise-=22
   if kind=='grass':noise+=5*math.sin(x*math.tau*8/255)*math.cos(y*math.tau*6/255)
   px[x,y]=tuple(max(0,min(255,round(v+noise))) for v in base)
 for x in range(255):px[x,255]=px[x,0]
 for y in range(256):px[255,y]=px[0,y]
 im.save(out/f'{kind}.png');images[kind]=im;buf=io.BytesIO();im.save(buf,format='PNG');embedded[kind]='data:image/png;base64,'+base64.b64encode(buf.getvalue()).decode()
atlas=Image.new('RGB',(512,512))
for i,im in enumerate(images.values()):atlas.paste(im,((i%2)*256,(i//2)*256))
atlas.save(out/'atlas.png');(out/'embedded.json').write_text(json.dumps(embedded,separators=(',',':')))
(out/'SOURCE.md').write_text('''# Ground materials\n\nOriginal procedural overhead textures generated by `tools/build-ground-art.py`; no third-party imagery or generative model assets. Fixed seed, flat lighting, no baked shadows or road markings. Materials: asphalt, paving, curb, grass. Opposite pixel borders match exactly. Game-world pattern scale: 256 pixels / 24 texels per world unit; cached world map resolution 3 pixels per world unit; marks and intersections are drawn separately into a cached world map. Atlas quadrants: asphalt / paving / curb / grass. Grass-to-paving transitions use feathered world-space edges, not tiled rectangular decals.\n''')
print('Generated four seamless materials and atlas')
